import Foundation
import FortiVPNShared

/// The scripts the admin prompt runs to install or remove the helper (PLAN.md 2.6).
///
/// Only a fixed header changes between installs, and every value in it is
/// validated here and shell-quoted: the allowed UID and leaf hash (through
/// `HelperLaunchArguments`), the bundled helper's path and sha256, and the plist.
/// Everything else is a constant from `AppIdentity`. The body is fixed text that
/// uses the header's variables, always in double quotes.
public enum HelperInstallScript {
    public struct Refusal: Error, Equatable, CustomStringConvertible {
        public let description: String
    }

    /// Where the app bundle keeps the helper binary.
    public static let bundledHelperName = "FortiVPNHelper"
    /// Homebrew's openfortivpn on Apple Silicon: the only source of the copy (S2).
    public static let homebrewOpenFortiVPN = "/opt/homebrew/bin/openfortivpn"

    /// The launchd job. `RunAtLoad` lets the helper sweep a crashed session at boot;
    /// XPC starts it on demand otherwise. No output paths: it logs through `os.Logger`.
    public static func plist(arguments: HelperLaunchArguments) -> String {
        let plist: [String: Any] = [
            "Label": AppIdentity.helperLabel,
            "ProgramArguments": [AppIdentity.helperExecutablePath] + arguments.arguments,
            "MachServices": [HelperTransport.machServiceName: true],
            "RunAtLoad": true,
        ]
        // A dictionary of strings and booleans always serializes.
        let data = try! PropertyListSerialization.data(fromPropertyList: plist, format: .xml, options: 0)
        return String(decoding: data, as: UTF8.self)
    }

    /// The install script. `bundledHelper` is the helper inside the app bundle and
    /// `bundledHelperSHA256` its hash as the app read it; the script refuses a copy
    /// that differs, so swapping the file during the prompt gains nothing.
    public static func install(arguments: HelperLaunchArguments, bundledHelper: String, bundledHelperSHA256: String) throws -> String {
        guard isSafePath(bundledHelper) else { throw Refusal(description: "The app's location cannot be used for installing; move the app to /Applications.") }
        guard bundledHelperSHA256.utf8.count == 64, bundledHelperSHA256.utf8.allSatisfy({ (48...57).contains($0) || (97...102).contains($0) }) else {
            throw Refusal(description: "Bad helper hash.")
        }
        return header + """
        bundled_helper=\(Commands.shellQuote(bundledHelper))
        bundled_helper_sha256=\(Commands.shellQuote(bundledHelperSHA256))
        plist_xml=\(Commands.shellQuote(plist(arguments: arguments)))


        """ + checks + installBody
    }

    public static func uninstall() -> String {
        header + checks + uninstallBody
    }

    /// Absolute, canonical, printable, and not too long. It is quoted anyway; this
    /// keeps anything odd out of the script and its error messages.
    static func isSafePath(_ path: String) -> Bool {
        let components = path.split(separator: "/", omittingEmptySubsequences: false).dropFirst()
        return path.hasPrefix("/") && path.utf8.count <= 1024
            && components.allSatisfy { !$0.isEmpty && $0 != "." && $0 != ".." }
            && path.unicodeScalars.allSatisfy { $0.value >= 0x20 && $0.value != 0x7f }
    }

    private static let header = """
    #!/bin/bash
    # FortiVPNTray helper, generated by the app (PLAN.md 2.6). Runs as root.
    set -euo pipefail
    export PATH=/usr/bin:/bin:/usr/sbin:/sbin
    export LC_ALL=C
    umask 022
    label=\(Commands.shellQuote(AppIdentity.helperLabel))
    helper=\(Commands.shellQuote(AppIdentity.helperExecutablePath))
    plist=\(Commands.shellQuote(AppIdentity.launchDaemonPlistPath))
    dotd=\(Commands.shellQuote(AppIdentity.openfortivpnDirectory))
    support=\(Commands.shellQuote(AppIdentity.helperSupportDirectory))
    run_dir=\(Commands.shellQuote(AppIdentity.helperRunDirectory))
    state_file=\(Commands.shellQuote(AppIdentity.helperStateFile))
    old_socket=\(Commands.shellQuote(AppIdentity.socketPath))
    old_log=\(Commands.shellQuote(AppIdentity.helperLogPath))
    source_binary=\(Commands.shellQuote(homebrewOpenFortiVPN))
    verify_flag=\(Commands.shellQuote(HelperLaunchArguments.verifyInstallFlag))


    """

    /// Run before anything else, after every variable is set.
    private static let checks = """
    die() { echo "$*" >&2; exit 1; }
    # set -e stops at the first failing command; say which, so the prompt's error is useful.
    trap 'echo "Stopped at line $LINENO: $BASH_COMMAND" >&2' ERR
    [[ "$(id -u)" -eq 0 ]] || die "The helper script must run as root."
    # Nothing below may follow a link someone else put where a file of ours goes.
    for path in "$helper" "$plist" "$dotd" "$support"; do
      [[ ! -L "$path" ]] || die "$path is a symbolic link; refusing to continue."
    done

    """

    private static let installBody = #"""
    [[ "$(uname -m)" == arm64 ]] || die "The helper supports Apple Silicon only."
    [[ -e "$source_binary" ]] || die "Homebrew's openfortivpn is missing. Install it with: brew install openfortivpn"
    [[ -f "$bundled_helper" ]] || die "The helper is missing from the app. Rebuild the app."

    # 1. Stop the running helper. The Rust helper used the same label and path.
    launchctl bootout "system/$label" 2>/dev/null || true
    rm -f "$old_socket" "$old_log"

    # 2. The helper binary, only if it is the file the app hashed.
    install -d -o root -g wheel -m 755 /Library/PrivilegedHelperTools
    rm -f "$helper.new"
    install -o root -g wheel -m 755 "$bundled_helper" "$helper.new"
    if [[ "$(shasum -a 256 "$helper.new" | awk '{ print $1 }')" != "$bundled_helper_sha256" ]]; then
      rm -f "$helper.new"
      die "The app's helper changed during installation; nothing was installed."
    fi
    mv -f "$helper.new" "$helper"

    # 3. The openfortivpn copy (S2), built in "$dotd.new" with load paths that point at
    #    "$dotd", then moved into place. Each file is copied first and only the copy is
    #    inspected, so a file that changes under /opt/homebrew cannot differ from what was checked.
    stage="$dotd.new"
    rm -rf "$stage"
    mkdir -m 755 "$stage" "$stage/lib" "$stage/certs"
    staged=()
    origins=()
    origin_hashes=()
    sha256_of() { shasum -a 256 "$1" | awk '{ print $1 }'; }
    origin_of() {
      local index=0
      while [[ $index -lt ${#staged[@]} ]]; do
        if [[ "${staged[$index]}" == "$1" ]]; then echo "${origins[$index]}"; return; fi
        index=$((index + 1))
      done
    }
    copy_in() { # <resolved source> <file in the stage>
      [[ "$1" =~ ^/[A-Za-z0-9._+@/-]+$ ]] || die "Unexpected library path: $1"
      [[ -f "$1" ]] || die "Not a regular file: $1"
      cp "$1" "$2"
      chmod u+w "$2"
      staged+=("$2")
      origins+=("$1")
      origin_hashes+=("$(sha256_of "$2")")
    }
    non_system_libraries() {
      otool -L "$1" | tail -n +2 | awk '{ print $1 }' | grep -Ev '^(/usr/lib/|/System/)' || true
    }

    binary_real="$(realpath "$source_binary")" || die "Cannot resolve $source_binary"
    copy_in "$binary_real" "$stage/openfortivpn"
    queue=("$stage/openfortivpn")
    next=0
    while [[ $next -lt ${#queue[@]} ]]; do
      current="${queue[$next]}"
      next=$((next + 1))
      # Read every load command first: install_name_tool below rewrites "$current",
      # and otool must never read a file while it is being rewritten.
      references=()
      while IFS= read -r line; do references+=("$line"); done < <(non_system_libraries "$current")
      ref_index=0
      while [[ $ref_index -lt ${#references[@]} ]]; do
        reference="${references[$ref_index]}"
        ref_index=$((ref_index + 1))
        [[ -n "$reference" ]] || continue
        case "$reference" in
          "$dotd"/lib/*) continue ;;
          @*) die "$reference: @rpath and @loader_path references are not handled." ;;
          /*) ;;
          *) die "$current loads a relative path: $reference" ;;
        esac
        real="$(realpath "$reference")" || die "Cannot resolve $reference"
        name="$(basename "$real")"
        [[ "$name" =~ ^[A-Za-z0-9._+-]+$ ]] || die "Unexpected library name: $name"
        if [[ -e "$stage/lib/$name" ]]; then
          [[ "$(origin_of "$stage/lib/$name")" == "$real" ]] || die "Two different libraries are both called $name."
        else
          copy_in "$real" "$stage/lib/$name"
          install_name_tool -id "$dotd/lib/$name" "$stage/lib/$name" 2>/dev/null
          queue+=("$stage/lib/$name")
        fi
        install_name_tool -change "$reference" "$dotd/lib/$name" "$current" 2>/dev/null
      done
    done

    # Rewriting load commands breaks the signature, and arm64 runs only signed code.
    files=("$stage/openfortivpn")
    while IFS= read -r library; do files+=("$library"); done < <(find "$stage/lib" -type f | sort)
    for file in "${files[@]}"; do
      codesign --force --sign - "$file" 2>/dev/null
      if [[ "$file" == "$stage/openfortivpn" ]]; then chmod 755 "$file"; else chmod 644 "$file"; fi
    done

    # The manifest OpenFortiVPNInstall.verify() reads. The set hash covers one
    # "<sha256>  <file>" line per file: the binary first, then lib/ sorted bytewise.
    # The copy is never run here: as root and without the helper's OpenSSL
    # environment it could read user-writable OpenSSL configuration.
    json_string() { printf '"%s"' "$(printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g')"; }
    keg="$(basename "$(dirname "$(dirname "$binary_real")")")"
    [[ "$keg" =~ ^[0-9A-Za-z._-]+$ ]] || keg=""
    openssl_version="$(strings -a "$stage"/lib/libcrypto.*.dylib 2>/dev/null | grep -m1 -E '^OpenSSL [0-9]+\.[0-9]+\.[0-9]+' || true)"
    set_hash="$(for file in "${files[@]}"; do printf '%s  %s\n' "$(sha256_of "$file")" "${file#"$stage"/}"; done | shasum -a 256 | awk '{ print $1 }')"
    source_set_hash="$(for file in "${files[@]}"; do
      index=0
      while [[ $index -lt ${#staged[@]} ]]; do
        [[ "${staged[$index]}" == "$file" ]] && printf '%s  %s\n' "${origin_hashes[$index]}" "${origins[$index]}"
        index=$((index + 1))
      done
    done | shasum -a 256 | awk '{ print $1 }')"
    {
      printf '{\n'
      printf '  "openfortivpn_version": %s,\n' "$(json_string "${keg%_*}")"
      printf '  "openssl_version": %s,\n' "$(json_string "$openssl_version")"
      printf '  "homebrew_keg": %s,\n' "$(json_string "$keg")"
      printf '  "set_sha256": %s,\n' "$(json_string "$set_hash")"
      printf '  "source_set_sha256": %s,\n' "$(json_string "$source_set_hash")"
      printf '  "files": [\n'
      last=$((${#files[@]} - 1))
      position=0
      for file in "${files[@]}"; do
        index=0
        while [[ "${staged[$index]}" != "$file" ]]; do index=$((index + 1)); done
        printf '    { "file": %s, "sha256": %s, "source": %s, "source_sha256": %s }' \
          "$(json_string "${file#"$stage"/}")" "$(json_string "$(sha256_of "$file")")" \
          "$(json_string "${origins[$index]}")" "$(json_string "${origin_hashes[$index]}")"
        [[ $position -lt $last ]] && printf ','
        printf '\n'
        position=$((position + 1))
      done
      printf '  ]\n}\n'
    } > "$stage/manifest.json"
    chmod 644 "$stage/manifest.json"
    chown -R root:wheel "$stage"
    chmod 755 "$stage" "$stage/lib" "$stage/certs"
    rm -rf "$dotd"
    mv "$stage" "$dotd"

    # 4. The helper's own directories; it checks them again before every use.
    for directory in "$support" "$run_dir"; do
      [[ ! -L "$directory" ]] || die "$directory is a symbolic link; refusing to continue."
      mkdir -p "$directory"
      chown root:wheel "$directory"
      chmod 700 "$directory"
    done

    # 5. The launchd job.
    rm -f "$plist"
    printf '%s' "$plist_xml" > "$plist"
    chown root:wheel "$plist"
    chmod 644 "$plist"
    plutil -lint "$plist" >/dev/null || die "The launchd job file is not valid."

    # 6. The helper checks the copy exactly as it will before every connect.
    "$helper" "$verify_flag" || die "The openfortivpn copy failed the helper's check; the helper was not started."

    launchctl bootstrap system "$plist"
    echo "Installed $label."
    """#

    private static let uninstallBody = #"""
    # A session's state file exists until its cleanup ran; removing the helper now
    # would leave its routes and DNS behind.
    [[ ! -e "$state_file" ]] || die "A VPN session is active, or one was not cleaned up yet. Disconnect first, or repair the helper so it can clean up, then uninstall."

    launchctl bootout "system/$label" 2>/dev/null || true
    rm -f "$helper" "$helper.new" "$plist" "$old_socket" "$old_log"
    rm -rf "$dotd" "$dotd.new" "$support"
    echo "Removed $label."
    """#
}
