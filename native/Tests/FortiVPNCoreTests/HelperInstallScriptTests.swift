    /// Every variable that holds a path is expanded inside double quotes, so a space
    /// ("/Library/Application Support") never splits it.
    @Test func testPathVariablesAreAlwaysQuoted() throws {
        let paths = ["helper", "plist", "dotd", "support", "run_dir", "state_file", "old_socket", "old_log", "source_binary",
                     "bundled_helper", "stage", "path", "directory", "file", "current", "reference", "real", "binary_real"]
        for script in [try HelperInstallScript.install(arguments: try Self.signed(), bundledHelper: Self.bundled, bundledHelperSHA256: Self.hash),
                       HelperInstallScript.uninstall()] {
            for line in script.split(separator: "\n") where !line.trimmingCharacters(in: .whitespaces).hasPrefix("#") {
                for name in paths {
                    for form in ["$" + name, "${" + name] {
                        var search = line.startIndex
                        while let range = line.range(of: form, range: search..<line.endIndex) {
                            let after = range.upperBound < line.endIndex ? line[range.upperBound] : " "
                            let isName = form.hasPrefix("${") || !(after.isLetter || after.isNumber || after == "_")
                            if isName {
                                #expect(range.lowerBound > line.startIndex && line[line.index(before: range.lowerBound)] == "\"" || isInsideDoubleQuotes(line, range.lowerBound),
                                        "unquoted \(form) in: \(line)")
                            }
                            search = range.upperBound
                        }
                    }
                }
            }
        }
    }

    /// Whether `index` falls inside a double-quoted word on this line (single quotes and `$(...)` nesting tracked).
    private func isInsideDoubleQuotes(_ line: Substring, _ index: Substring.Index) -> Bool {
        var stack: [Character] = []   // '"' for a quoted string, '(' for $( inside one
        var position = line.startIndex
        while position < index {
            let character = line[position]
            let next = line.index(after: position)
            switch (stack.last, character) {
            case (nil, "'"):
                position = line[next...].firstIndex(of: "'").map { line.index(after: $0) } ?? line.endIndex
                continue
            case (nil, "\""), ("(", "\""): stack.append("\"")
            case ("\"", "\""): stack.removeLast()
            case (_, "$") where next < line.endIndex && line[next] == "(":
                stack.append("(")
                position = line.index(after: next)
                continue
            case ("(", ")"): stack.removeLast()
            default: break
            }
            position = next
        }
        return stack.last == "\""
    }

    @Test func testUninstallScript() {
        let script = HelperInstallScript.uninstall()
        #expect(script.contains("[[ ! -e \"$state_file\" ]] || die \"A VPN session is active"))
        let refuse = script.range(of: "[[ ! -e \"$state_file\" ]]")!.lowerBound
        let bootout = script.range(of: "launchctl bootout")!.lowerBound
        let remove = script.range(of: "rm -rf \"$dotd\" \"$dotd.new\" \"$support\"")!.lowerBound
        #expect(refuse < bootout && bootout < remove, "refuse first, then stop the helper, then remove its files")
        #expect(script.contains("rm -f \"$helper\" \"$helper.new\" \"$plist\" \"$old_socket\" \"$old_log\""))
        #expect(!script.contains("Library/Preferences") && !script.contains("profiles"), "profiles are left alone")
    }

    @Test func testInstallOrder() throws {
        let script = try HelperInstallScript.install(arguments: try Self.signed(), bundledHelper: Self.bundled, bundledHelperSHA256: Self.hash)
        func position(_ text: String) throws -> String.Index { try #require(script.range(of: text), "\(text)").lowerBound }
        let steps = [
            "[[ -e \"$source_binary\" ]] || die \"Homebrew's openfortivpn is missing",
            "launchctl bootout \"system/$label\"",
            "rm -f \"$old_socket\" \"$old_log\"",
            "!= \"$bundled_helper_sha256\" ]]",
            "mv -f \"$helper.new\" \"$helper\"",
            "mkdir -m 755 \"$stage\" \"$stage/lib\" \"$stage/certs\"",
            "codesign --force --sign - \"$file\"",
            "} > \"$stage/manifest.json\"",
            "mv \"$stage\" \"$dotd\"",
            "printf '%s' \"$plist_xml\" > \"$plist\"",
            "\"$helper\" \"$verify_flag\" || die",
            "launchctl bootstrap system \"$plist\"",
        ]
        let positions = try steps.map(position)
        #expect(positions == positions.sorted())
        #expect(!script.contains("ossl-modules"))
        #expect(!script.contains("/tmp"), "root creates nothing under /tmp")
    }

    // MARK: Admin prompt

    @Test func testAdministratorCommandQuotesTheWholeScript() throws {
        let script = "echo 'it''s' \"$HOME\" `id`\n"
        let command = Commands.administratorCommand(script: script)
        #expect(command.hasPrefix("/bin/bash -c '"))
        // The shell `do shell script` uses sees one word: exactly the script.
        let result = try bash(["-c", "printf '%s' " + String(command.dropFirst("/bin/bash -c ".count))])
        #expect(result.output == script)
    }

    @Test func testAdministratorErrorKeepsTheScriptsMessage() {
        #expect(Commands.administratorError("0:123: execution error: Homebrew's openfortivpn is missing. Install it with: brew install openfortivpn (1)\n")
                == "Homebrew's openfortivpn is missing. Install it with: brew install openfortivpn")
        #expect(Commands.administratorError("0:84: execution error: User canceled. (-128)") == "The administrator prompt was cancelled.")
    }
