    @Test func testBadValuesAreRefused() throws {
        for path in ["", "relative/FortiVPNHelper", "/a/../b", "/a//b", "/a/./b", "/a/b/", "/a\nb", "/a\rb", "/a\0b", "/a\u{7f}b",
                     "/" + String(repeating: "x", count: 1024)] {
            #expect(throws: HelperInstallScript.Refusal.self, "\(path)") {
                try HelperInstallScript.install(arguments: try Self.signed(), bundledHelper: path, bundledHelperSHA256: Self.hash)
            }
        }
        for hash in ["", String(repeating: "A", count: 64), String(repeating: "a", count: 63), String(repeating: "g", count: 64), Self.hash + "'"] {
            #expect(throws: HelperInstallScript.Refusal.self, "\(hash)") {
                try HelperInstallScript.install(arguments: try Self.signed(), bundledHelper: Self.bundled, bundledHelperSHA256: hash)
            }
        }
        // UID and leaf are refused before a script exists.
        #expect(throws: HelperLaunchArguments.ParseError.self) { try HelperLaunchArguments(allowedUID: 0, callerCheck: .uidOnly) }
        #expect(throws: HelperLaunchArguments.ParseError.self) { try HelperLaunchArguments(allowedUID: 501, callerCheck: .signed(leafSHA1: "x'; rm -rf /")) }
    }

    /// A failing command stops the script and says where; a refusal says why. Run as the
    /// test user on a harmless script, never the installer itself.
    @Test func testFailuresAreReported() throws {
        let checks = HelperInstallScript.uninstall().components(separatedBy: "[[ \"$(id -u)\" -eq 0 ]]")[0]
        #expect(checks.contains("trap 'echo \"Stopped at line $LINENO: $BASH_COMMAND\" >&2' ERR"))
        let failing = try bash(["-c", "set -euo pipefail\n" + checks.components(separatedBy: "set -euo pipefail\n")[1] + "/usr/bin/false\necho unreachable\n"])
        #expect(failing.status != 0)
        #expect(failing.output.contains("Stopped at line") && failing.output.contains("/usr/bin/false"))
        #expect(!failing.output.contains("unreachable"))
    }

