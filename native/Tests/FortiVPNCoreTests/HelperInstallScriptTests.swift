/// The installer and uninstaller scripts (PLAN.md 2.6). They are generated and
/// checked here; only the maintainer runs them. Nothing is executed as root.
struct HelperInstallScriptTests {
    static let leaf = "0123456789ABCDEF0123456789ABCDEF01234567"
    static let hash = String(repeating: "ab", count: 32)
    static let bundled = "/Applications/FortiVPNTray.app/Contents/Resources/FortiVPNHelper"

    static func signed() throws -> HelperLaunchArguments { try HelperLaunchArguments(allowedUID: 501, callerCheck: .signed(leafSHA1: leaf)) }
    static func uidOnly() throws -> HelperLaunchArguments { try HelperLaunchArguments(allowedUID: 502, callerCheck: .uidOnly) }

    private func bash(_ arguments: [String]) throws -> (status: Int32, output: String) {
        let process = Process(), pipe = Pipe()
        process.executableURL = URL(fileURLWithPath: "/bin/bash")
        process.arguments = arguments
        process.environment = ["PATH": "/usr/bin:/bin"]
        process.standardOutput = pipe
        process.standardError = pipe
        process.standardInput = FileHandle.nullDevice
        try process.run()
        let data = pipe.fileHandleForReading.readDataToEndOfFile()
        process.waitUntilExit()
        return (process.terminationStatus, String(decoding: data, as: UTF8.self))
    }

    /// The lines that set variables, evaluated on their own: what the script would see.
    private func values(of script: String, _ names: [String]) throws -> [String] {
        let assignments = script.split(separator: "\n", omittingEmptySubsequences: false)
            .prefix { !$0.hasPrefix("die()") }
            .filter { !$0.hasPrefix("set ") }
            .joined(separator: "\n")
        let output = try bash(["-c", assignments + "\n" + names.map { "printf '%s\\0' \"$\($0)\"" }.joined(separator: "\n")])
        #expect(output.status == 0, "\(output.output)")
        return output.output.split(separator: "\0", omittingEmptySubsequences: false).dropLast().map(String.init)
    }

